print("Essa é uma 'string' (str).")  # Esse exemplo mostra como colocar uma string em aspas duplas, e tambem
print('Essa é uma "string" (str).')  # para utilizar aspas simples caso a dupla já tenha sido usada e vice versa
print("Essa é uma \"string\" (str).")  # esse exemplo mostra como utilizar a barra de escape \
print('Essa é uma \"string\" (str).')  # para que o código não leia a aspas
print(r'Essa é uma \"string\" (str).')  # o 'r' ignora qualquer comando dentro da string, como a \ por exemplo
print('Essa é uma \n (str).')  # \n representa quebra de linha




