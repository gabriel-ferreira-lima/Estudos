'''
+   - adição
-   - subtração
*   - multiplicação
/   - divisão
//  - divisão inteira, arredonda o numero
**  - tira a potencia de um numero
%   - tira o resto da divisão
()  - altera a precedencia, por exemplo faz adição primeiro que multiplicação
'''

print(10 + 10)
print(10 - 5)
print(10 * 10)
print(10 / 10)
print(10.3 // 1.2)
print(2 ** 16)
print(10 % 3)

print ((10 + 5) * 10)

